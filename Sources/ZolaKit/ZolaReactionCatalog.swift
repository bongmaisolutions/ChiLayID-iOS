/// Display aliases from Zalo iOS 261002's bundled emoji-invert.json (Unicode entries only).
/// Proprietary image-only icons are not guessed. Outgoing reaction types require independent wire proof.
public enum ZolaReactionCatalog {
    public static func displayEmoji(for raw: String) -> String? {
        let icon = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        switch icon {
        case "/-heart", "❤️", "❤": return "❤️"
        case "/-strong", "👍": return "👍"
        case ":>", "😆": return "😆"
        case ":-o", ":o", "😮": return "😮"
        case ":-((", "😢": return "😢"
        case ":-h", "😡": return "😡"
        default: break
        }
        if let emoji = aliases[icon] { return emoji }
        if nativeTypes[icon] != nil { return icon }
        // One extended grapheme: preserves skin tones, flags and ZWJ sequences without accepting text.
        guard icon.count == 1,
              icon.unicodeScalars.contains(where: { $0.properties.isEmojiPresentation || $0.value == 0xFE0F }),
              icon.unicodeScalars.allSatisfy({ $0.properties.isEmoji || [0xFE0F, 0x200D, 0x20E3].contains($0.value) }) else { return nil }
        return icon
    }

    /// Types captured from the real 261002 ReactionRepoBridge without sending a request.
    public static func wireReaction(for raw: String) -> (rIcon: String, rType: Int, displayEmoji: String)? {
        let trimmed = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        if trimmed.isEmpty { return ("", -1, "") }
        guard let emoji = displayEmoji(for: trimmed) else { return nil }
        switch emoji {
        case "❤️": return ("/-heart", 5, emoji)
        case "👍": return ("/-strong", 3, emoji)
        case "😆": return (":>", 0, emoji)
        case "😮": return (":-o", 32, emoji)
        case "😢": return (":-((", 2, emoji)
        case "😡": return (":-h", 20, emoji)
        default:
            guard let type = nativeTypes[emoji] else { return nil }
            return (emoji, type, emoji)
        }
    }

    public static var supportedEmoji: [String] { nativeTypes.keys.sorted() }
    private static let nativeTypes: [String: Int] = {
